"""Generate deployment SQL without changing historical EF migrations.

SQL Server binds static statements in skipped IF blocks and before preceding
ALTER statements in the same batch. Compile each EF-guarded operation only when
its migration actually needs applying, after earlier operations have completed.
"""
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[1]
raw = root / "artifacts/family-migration-raw.sql"
raw.parent.mkdir(exist_ok=True)
subprocess.run([
    "dotnet", "ef", "migrations", "script", "--idempotent", "--output", str(raw),
    "--project", str(root / "src/Wasla/Wasla.Infrastructure.EntityFrameworkCore.SqlServer"),
    "--startup-project", str(root / "src/Wasla/Wasla.Api"),
], cwd=root, check=True)
sql = raw.read_text(encoding="utf-8-sig")
pattern = re.compile(
    r"^(IF NOT EXISTS \(\n    SELECT \* FROM \[__EFMigrationsHistory\]\n"
    r"    WHERE \[MigrationId\] = N'[^']+'\n\)\nBEGIN\n)(.*?)(^END;[ \t]*$)",
    re.MULTILINE | re.DOTALL,
)
def deferred(match):
    body = match[2].replace("'", "''")
    return match[1] + "    EXEC(N'" + body + "');\n" + match[3]
sql, count = pattern.subn(deferred, sql)
if count < 100:
    raise RuntimeError("Unexpected EF script format; inspect before deployment.")
header = "-- Generated by tools/generate-family-migration.py. EF history guards and transactions retained.\n-- Dynamic per-operation compilation supports both clean databases and idempotent upgrades.\n"
(root / "docs/family-self-service/MIGRATION.sql").write_text(header + sql, encoding="utf-8")
print(f"Generated idempotent deployment SQL with {count} deferred migration operations.")
